"""
Evaluate EXPRESS-Bench results.
Read results generated by run_express_bench_evaluation_vlm_only.py, use GPT-4o for evaluation, and generate EAC scores.
"""

import json
import os
import time
import pickle
import argparse
import numpy as np
from openai import OpenAI
from typing import Optional
import re
from tqdm import tqdm

# Initialize OpenAI client
client = OpenAI(
    api_key='',
    base_url=''
)

def load_prompt(prompt_file):
    """Load prompt file."""
    with open(prompt_file, 'r', encoding='utf-8') as f:
        content = f.read()
    return content

def call_gpt4o(system_prompt, user_prompt, image_path=None, max_retries=5):
    """Call GPT-4o API."""
    retry_count = 0
    
    while retry_count < max_retries:
        try:
            messages = [
                {"role": "system", "content": system_prompt},
            ]
            
            # Construct user message
            user_content = []
            user_content.append({"type": "text", "text": user_prompt})
            
            # If image exists, add image
            if image_path and os.path.exists(image_path):
                import base64
                with open(image_path, "rb") as image_file:
                    base64_image = base64.b64encode(image_file.read()).decode('utf-8')
                user_content.append({
                    "type": "image_url",
                    "image_url": {
                        "url": f"data:image/jpeg;base64,{base64_image}"
                    }
                })
            
            messages.append({"role": "user", "content": user_content})
            
            completion = client.chat.completions.create(
                model="gpt-4o-mini",  # "gpt-4o"
                messages=messages,
                temperature=0.7,
                max_tokens=512
            )
            return completion.choices[0].message.content
        except Exception as e:
            print(f"API call error (attempt {retry_count + 1}/{max_retries}): {e}")
            retry_count += 1
            if retry_count < max_retries:
                time.sleep(3)
            else:
                print(f"Max retries reached, skipping this question")
                return None
    
    return None

def extract_system_and_user_prompt(prompt_content):
    """Extract system and user parts from prompt file."""
    lines = prompt_content.strip().split('\n')
    
    system_prompt = ""
    user_prompt = ""
    current_section = None
    
    for line in lines:
        if line.strip() == "[system]:":
            current_section = "system"
            continue
        elif line.strip() == "[user]:":
            current_section = "user"
            continue
        
        if current_section == "system":
            system_prompt += line + "\n"
        elif current_section == "user":
            user_prompt += line + "\n"
    
    return system_prompt.strip(), user_prompt.strip()

def parse_eac_scores(response):
    """
    Extract EAC two scores from GPT-4o response.
    Expected format: "Your mark: 0.5, 3" or "1, 5", etc.
    Returns: (image_alignment_score, accuracy_score)
    """
    if not response:
        return None, None
    
    # Try multiple regex patterns to extract scores
    patterns = [
        r'Your mark:\s*(\d+\.?\d*)\s*,\s*(\d+)',  # "Your mark: 0.5, 3"
        r'(\d+\.?\d*)\s*,\s*(\d+)',  # "0.5, 3"
        r'mark:\s*(\d+\.?\d*)\s*,\s*(\d+)',  # "mark: 1, 5"
    ]
    
    for pattern in patterns:
        matches = re.findall(pattern, response)
        if matches:
            try:
                score1 = float(matches[0][0])
                score2 = int(matches[0][1])
                # Validate score range
                if 0 <= score1 <= 1 and 1 <= score2 <= 5:
                    return score1, score2
            except (ValueError, IndexError):
                continue
    
    print(f"Warning: Failed to parse scores from response: {response}")
    return None, None

def aggregate_split_results(output_dir):
    """Aggregate result files across all splits (V2 - supports express_bench_info)."""
    # Find all gpt_answer files
    gpt_answer_files = []
    for file in os.listdir(output_dir):
        if file.startswith("gpt_answer_") and file.endswith(".json"):
            gpt_answer_files.append(file)
    
    if not gpt_answer_files:
        print(f"No gpt_answer files found in directory: {output_dir}")
        return None, None, None
    
    # Aggregate all results
    all_gpt_answers = {}
    all_path_lengths = {}
    all_express_info = {}
    
    for gpt_file in gpt_answer_files:
        # Extract ratio info
        parts = gpt_file.replace("gpt_answer_", "").replace(".json", "").split("_")
        start_ratio = float(parts[0])
        end_ratio = float(parts[1])
        
        # Read gpt_answer
        with open(os.path.join(output_dir, gpt_file), 'r') as f:
            gpt_answers = json.load(f)
            
            # Handle two formats: dict format and list format
            if isinstance(gpt_answers, list):
                # List format: [{"question_id": "xxx", "answer": "yyy"}, ...]
                for item in gpt_answers:
                    all_gpt_answers[item['question_id']] = item['answer']
            elif isinstance(gpt_answers, dict):
                # Dict format: {"question_id": "answer", ...}
                all_gpt_answers.update(gpt_answers)
            else:
                print(f"Warning: Unknown gpt_answer format: {type(gpt_answers)}")
        
        # Read corresponding path_length file
        path_file = f"path_length_list_{start_ratio}_{end_ratio}.pkl"
        if os.path.exists(os.path.join(output_dir, path_file)):
            with open(os.path.join(output_dir, path_file), 'rb') as f:
                path_lengths = pickle.load(f)
                all_path_lengths.update(path_lengths)
        
        # ⭐ Read express_bench_info file
        express_info_file = f"express_bench_info_{start_ratio}_{end_ratio}.json"
        if os.path.exists(os.path.join(output_dir, express_info_file)):
            with open(os.path.join(output_dir, express_info_file), 'r') as f:
                express_info = json.load(f)
                all_express_info.update(express_info)
            print(f"✓ Found EXPRESS-Bench info file: {express_info_file}")
        else:
            print(f"⚠️  EXPRESS-Bench info file not found: {express_info_file}")
    
    print(f"Aggregated {len(gpt_answer_files)} split files")
    print(f"Total {len(all_gpt_answers)} answers")
    print(f"EXPRESS-Bench info: {len(all_express_info)} questions")
    
    return all_gpt_answers, all_path_lengths, all_express_info

def evaluate_express_bench(
    result_dir,
    questions_file,
    prompt_file,
    output_file,
    episode_image_dir=None,
    random_answer_prompt_file=None
):
    """
    Evaluate EXPRESS-Bench results (V2 version).
    """
    
    print("Loading results data...")
    # Aggregate results from all splits
    gpt_answers, path_lengths, express_info = aggregate_split_results(result_dir)
    
    if gpt_answers is None:
        print("Failed to load results data")
        return
    
    print(f"Answers data loaded, {len(gpt_answers)} total answers")
    
    print("Loading questions data...")
    with open(questions_file, 'r', encoding='utf-8') as f:
        questions_data = json.load(f)
    print(f"Questions data loaded, {len(questions_data)} total questions")
    
    print("Loading evaluation prompt...")
    prompt_content = load_prompt(prompt_file)
    system_prompt, user_prompt_template = extract_system_and_user_prompt(prompt_content)
    print("Prompt loaded successfully")
    
    # Load random_answer prompt (used for "blind" guess)
    random_answer_system_prompt = None
    random_answer_user_prompt = None
    if random_answer_prompt_file and os.path.exists(random_answer_prompt_file):
        print(f"Loading random_answer prompt: {random_answer_prompt_file}")
        random_answer_content = load_prompt(random_answer_prompt_file)
        random_answer_system_prompt, random_answer_user_prompt = extract_system_and_user_prompt(random_answer_content)
        print("Random answer prompt loaded successfully")
    else:
        print("⚠️  No random_answer prompt file provided, skipping regeneration of empty answers")
    
    # Create question_id to question_data mapping
    question_map = {q['question_id']: q for q in questions_data}
    
    results = []
    evaluated_count = 0
    
    # Count empty answers
    empty_answer_count = 0
    regenerated_answer_count = 0
    
    # Iterate through all answered questions
    for question_id, model_answer in tqdm(gpt_answers.items(), desc="Evaluation progress"):
        if question_id not in question_map:
            print(f"\nWarning: question_id {question_id} not in questions dataset")
            continue
        
        question_data = question_map[question_id]
        question = question_data['question']
        ground_truth_answer = question_data['answer']
        
        print(f"\nEvaluating question {question_id}")
        print(f"Question: {question}")
        print(f"Ground truth answer: {ground_truth_answer}")
        print(f"Raw model response: {model_answer}")
        
        # ⭐ Check if model answer is empty; if so, use GPT-4o-mini for "blind" guess
        if (model_answer is None or model_answer == "" or (isinstance(model_answer, str) and model_answer.strip() == "")):
            empty_answer_count += 1
            print(f"⚠️  Detected empty answer!")
            
            if random_answer_system_prompt is not None and random_answer_user_prompt is not None:
                print(f"🔄 Regenerating answer using GPT-4o-mini...")
                
                # Construct random_answer user prompt (question only, no images)
                random_user_prompt = f"{random_answer_user_prompt}\n\nQ: {question}\nA: "
                
                # Call GPT-4o-mini for "blind" guess
                regenerated_answer = call_gpt4o(
                    random_answer_system_prompt, 
                    random_user_prompt, 
                    image_path=None,  # Do not use image
                    max_retries=5
                )
                
                if regenerated_answer:
                    # Clean up answer format
                    regenerated_answer = regenerated_answer.replace("A:", "").strip()
                    model_answer = regenerated_answer
                    regenerated_answer_count += 1
                    print(f"✓ Regenerated answer: {model_answer}")
                else:
                    print(f"❌ Failed to regenerate answer, using empty string")
                    model_answer = ""
            else:
                print(f"⚠️  No random_answer prompt loaded, skipping regeneration")
                model_answer = ""
        
        print(f"Final model answer: {model_answer}")
        
        # Construct user prompt for evaluation
        eval_user_prompt = f"{user_prompt_template}\n"
        eval_user_prompt += f"Question: {question}\n"
        eval_user_prompt += f"Answer: {ground_truth_answer}\n"
        eval_user_prompt += f"Response: {model_answer}\n"
        
        # Try to find corresponding image (search from chosen_snapshot directory)
        image_path = None
        chosen_snapshot_dir = f"{episode_image_dir}/{question_id}/chosen_snapshot"
        
        if os.path.exists(chosen_snapshot_dir):
            # Get all image files in directory
            image_files = [f for f in os.listdir(chosen_snapshot_dir) 
                          if f.lower().endswith(('.png', '.jpg', '.jpeg'))]
            
            if image_files:
                # If multiple images, choose first
                image_path = os.path.join(chosen_snapshot_dir, image_files[0])
                print(f"✓ Found image: {image_path}")
                print(f"📷 This evaluation uses image input ({len(image_files)} image(s) total)")
            else:
                print(f"⚠️  Directory exists but no images found: {chosen_snapshot_dir}")
                print(f"📷 This evaluation has no image input")
        else:
            print(f"⚠️  chosen_snapshot directory not found: {chosen_snapshot_dir}")
            print(f"📷 This evaluation has no image input")
        
        # Call GPT-4o for evaluation
        eval_response = call_gpt4o(system_prompt, eval_user_prompt, image_path)
        
        if eval_response:
            print(f"Evaluation response: {eval_response}")
            
            # Parse EAC scores
            image_score, accuracy_score = parse_eac_scores(eval_response)
            
            if image_score is not None and accuracy_score is not None:
                print(f"Image alignment score: {image_score}, Accuracy score: {accuracy_score}")
                
                # Get path_length
                path_length = path_lengths.get(question_id, float('inf'))
                
                # ⭐ Get extra EXPRESS-Bench information
                if question_id in express_info:
                    geodesic_distance = express_info[question_id].get('geodesic_distance', float('inf'))
                    goal_dis = express_info[question_id].get('goal_dis', float('inf'))
                    print(f"✓ Using EXPRESS-Bench info: geodesic_dist={geodesic_distance:.3f}, goal_dis={goal_dis:.3f}")
                else:
                    # Fall back to dataset info
                    geodesic_distance = question_data.get("geodesic_distance", float('inf'))
                    goal_dis = float('inf')
                    print(f"⚠️  Using dataset info: geodesic_dist={geodesic_distance:.3f}")
                
                # Construct result entry
                result = {
                    "question_id": question_id,
                    "question": question,
                    "answer": ground_truth_answer,
                    "gen_answer": model_answer,
                    "category": question_data.get("category", "unknown"),
                    "EAC": f"Your mark: {image_score}, {accuracy_score}",
                    "image_alignment_score": image_score,
                    "accuracy_score": accuracy_score,
                    "path_len": path_length,
                    "geodesic_distance": geodesic_distance,
                    "goal_dis": goal_dis,
                    "evaluation_response": eval_response
                }
                results.append(result)
                evaluated_count += 1
            else:
                print("Score parsing failed")
                result = {
                    "question_id": question_id,
                    "question": question,
                    "answer": ground_truth_answer,
                    "gen_answer": model_answer,
                    "category": question_data.get("category", "unknown"),
                    "error": "Score parsing failed",
                    "evaluation_response": eval_response
                }
                results.append(result)
        else:
            print("Evaluation failed")
            result = {
                "question_id": question_id,
                "question": question,
                "answer": ground_truth_answer,
                "gen_answer": model_answer,
                "category": question_data.get("category", "unknown"),
                "error": "Evaluation API call failed"
            }
            results.append(result)
        
        # Save intermediate results every 10 questions
        if (evaluated_count + 1) % 10 == 0:
            print(f"\nSaving intermediate results...")
            with open(output_file, 'w', encoding='utf-8') as f:
                json.dump(results, f, ensure_ascii=False, indent=2)
    
    # Final save
    print(f"\nSaving final results to {output_file}...")
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    
    # Compute summary statistics
    valid_results = [r for r in results if 'accuracy_score' in r]
    if valid_results:
        avg_image_score = np.mean([r['image_alignment_score'] for r in valid_results])
        avg_accuracy = np.mean([r['accuracy_score'] for r in valid_results])
        print(f"\nEvaluation complete!")
        print(f"Successfully evaluated: {len(valid_results)}/{len(gpt_answers)}")
        print(f"Average Image alignment score: {avg_image_score:.2f}")
        print(f"Average accuracy score: {avg_accuracy:.2f}")
        print(f"\nEmpty answer statistics:")
        print(f"  Empty answers detected: {empty_answer_count}")
        print(f"  Successfully regenerated answers: {regenerated_answer_count}")
        print(f"  Regeneration success rate: {regenerated_answer_count}/{empty_answer_count if empty_answer_count > 0 else 0}")
        print(f"\nEvaluation results saved to: {output_file}")
    else:
        print("\nWarning: No successfully evaluated results")

